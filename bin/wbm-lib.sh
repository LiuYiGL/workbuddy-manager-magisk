#!/system/bin/sh
# WorkBuddy Manager（Android）宿主机侧公共函数。
# 由 wbm-ctl / wbm-supervise / customize.sh / service.sh source。
# 注意：这里运行在 Android 的 mksh/toybox 环境，不是 chroot 内的 Alpine。

WBM_ID=workbuddy_manager
WBM_MODDIR=${WBM_MODDIR:-/data/adb/modules/$WBM_ID}
WBM_DATA=${WBM_DATA:-/data/adb/workbuddy-manager}
WBM_ROOTFS=${WBM_ROOTFS:-$WBM_MODDIR/rootfs}
WBM_MOUNTDIR=/workbuddy
WBM_RUN=$WBM_DATA/run
WBM_LOGS=$WBM_DATA/logs

wbm_log() {
  printf '[%s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S' 2>/dev/null)" "$*"
}

wbm_busybox() {
  for p in "$WBM_MODDIR/busybox" /data/adb/magisk/busybox /data/adb/ksu/bin/busybox; do
    if [ -x "$p" ]; then echo "$p"; return 0; fi
  done
  command -v busybox 2>/dev/null || true
}

wbm_tar() {
  bb=$(wbm_busybox)
  if [ -n "$bb" ]; then "$bb" tar "$@"; else tar "$@"; fi
}

wbm_cp() {
  bb=$(wbm_busybox)
  if [ -n "$bb" ]; then "$bb" cp "$@"; else cp "$@"; fi
}

wbm_chroot() {
  if command -v chroot >/dev/null 2>&1; then
    chroot "$WBM_ROOTFS" "$@"
  else
    bb=$(wbm_busybox)
    if [ -n "$bb" ]; then "$bb" chroot "$WBM_ROOTFS" "$@"; else return 1; fi
  fi
}

# 进程存活，且不是僵尸（更新器会留下未回收的 zombie）。
wbm_alive() {
  pid=${1:-}
  [ -n "$pid" ] || return 1
  kill -0 "$pid" 2>/dev/null || return 1
  st=$(sed 's/.*) //' "/proc/$pid/stat" 2>/dev/null | cut -d' ' -f1)
  [ "$st" = Z ] && return 1
  return 0
}

wbm_read_pid() {
  f=$1
  [ -f "$f" ] || return 0
  pid=$(cat "$f" 2>/dev/null | tr -dc '0-9')
  [ -n "$pid" ] && echo "$pid"
}

# 进程命令行是否匹配（用于防止重启后 PID 被复用造成误判）。
wbm_pid_has() {
  pid=${1:-}; pat=${2:-}
  [ -n "$pid" ] && [ -n "$pat" ] || return 1
  [ -r "/proc/$pid/cmdline" ] || return 1
  tr '\000' ' ' < "/proc/$pid/cmdline" 2>/dev/null | grep -qE "$pat"
}

wbm_manager_pid()    { wbm_read_pid "$WBM_RUN/manager.pid"; }
wbm_upstream_pid()   { wbm_read_pid "$WBM_RUN/upstream.pid"; }
wbm_supervisor_pid() { wbm_read_pid "$WBM_RUN/supervisor.pid"; }

wbm_mounted() {
  if command -v mountpoint >/dev/null 2>&1; then
    mountpoint -q "$1" 2>/dev/null
  else
    grep -q " $1 " /proc/mounts 2>/dev/null
  fi
}

wbm_mount_one() {
  src=$1; dst=$2
  [ -d "$src" ] || return 0
  mkdir -p "$dst" 2>/dev/null || return 1
  wbm_mounted "$dst" && return 0
  mount -o bind "$src" "$dst" 2>/dev/null && return 0
  mount --bind "$src" "$dst" 2>/dev/null && return 0
  return 1
}

wbm_umount_one() {
  dst=$1
  [ -d "$dst" ] || return 0
  wbm_mounted "$dst" || return 0
  umount "$dst" 2>/dev/null && return 0
  bb=$(wbm_busybox)
  [ -n "$bb" ] && "$bb" umount "$dst" 2>/dev/null && return 0
  return 1
}

wbm_setup_mounts() {
  [ -d "$WBM_ROOTFS" ] || return 1
  mkdir -p \
    "$WBM_ROOTFS/proc" "$WBM_ROOTFS/dev" "$WBM_ROOTFS/sys" \
    "$WBM_ROOTFS/workbuddy" "$WBM_ROOTFS/tmp" "$WBM_ROOTFS/etc" \
    2>/dev/null || true

  wbm_mount_one /proc "$WBM_ROOTFS/proc" || wbm_log "警告：挂载 /proc 失败"
  wbm_mount_one /dev  "$WBM_ROOTFS/dev"  || wbm_log "警告：挂载 /dev 失败"
  [ -d /dev/pts ] && wbm_mount_one /dev/pts "$WBM_ROOTFS/dev/pts"
  wbm_mount_one /sys  "$WBM_ROOTFS/sys"  || wbm_log "警告：挂载 /sys 失败"
  wbm_mount_one "$WBM_DATA" "$WBM_ROOTFS/workbuddy" || {
    wbm_log "错误：无法把 $WBM_DATA 绑定到 chroot 的 /workbuddy"
    return 1
  }
  chmod 1777 "$WBM_ROOTFS/tmp" 2>/dev/null || true
  return 0
}

wbm_umount_all() {
  wbm_umount_one "$WBM_ROOTFS/workbuddy"
  wbm_umount_one "$WBM_ROOTFS/sys"
  wbm_umount_one "$WBM_ROOTFS/dev/pts"
  wbm_umount_one "$WBM_ROOTFS/dev"
  wbm_umount_one "$WBM_ROOTFS/proc"
}

# Android 的 DNS 由 netd 管理，没有可用的 /etc/resolv.conf。
# chroot 内是 musl，会直接读 /etc/resolv.conf，所以这里把当前网络的 DNS
# 写进去；用户可以放一份 $WBM_DATA/etc/resolv.conf 完全覆盖自动探测。
wbm_write_resolv() {
  dst=$WBM_ROOTFS/etc/resolv.conf
  [ -d "$WBM_ROOTFS/etc" ] || return 0

  if [ -f "$WBM_DATA/etc/resolv.conf" ]; then
    cp -f "$WBM_DATA/etc/resolv.conf" "$dst" 2>/dev/null && return 0
  fi

  names=""
  for p in net.dns1 net.dns2 net.dns3 net.dns4; do
    v=$(getprop "$p" 2>/dev/null | tr -d ' ')
    case "$v" in
      ''|0.0.0.0|::) ;;
      *) names="$names $v" ;;
    esac
  done

  if [ -z "$names" ] && command -v dumpsys >/dev/null 2>&1; then
    names=$(dumpsys connectivity 2>/dev/null \
      | sed -n 's/.*DnsAddresses: *\[\([^]]*\)\].*/\1/p' \
      | head -n 1 | tr ',' ' ')
  fi

  valid=""
  for n in $names; do
    n=$(printf '%s' "$n" | sed 's#^/##; s#^\[##; s#\]$##; s#%.*$##')
    case "$n" in
      *[!0-9a-fA-F:.]*) continue ;;
      *:*|*.*) valid="$valid $n" ;;
    esac
  done

  tmp=$dst.tmp
  {
    echo "# generated by WorkBuddy Manager ($(date '+%Y-%m-%d %H:%M:%S'))"
    if [ -n "$valid" ]; then
      for n in $valid; do echo "nameserver $n"; done
    else
      # 探测不到时给两个国内可达的公共 DNS；用户可用覆盖文件替换。
      echo "nameserver 223.5.5.5"
      echo "nameserver 119.29.29.29"
    fi
    echo "options timeout:2 attempts:2"
  } > "$tmp" 2>/dev/null && mv -f "$tmp" "$dst" 2>/dev/null
}

wbm_rotate() {
  f=$1; max=${2:-16777216}
  [ -f "$f" ] || return 0
  sz=$(wc -c < "$f" 2>/dev/null | tr -d ' ')
  case "$sz" in ''|*[!0-9]*) return 0 ;; esac
  [ "$sz" -gt "$max" ] && : > "$f" 2>/dev/null
}

wbm_http_ok() {
  wbm_chroot /usr/bin/curl -fsS --max-time 3 "$1" >/dev/null 2>&1
}

wbm_ensure_dirs() {
  mkdir -p \
    "$WBM_DATA/app" "$WBM_DATA/data" "$WBM_DATA/pylibs" \
    "$WBM_DATA/run" "$WBM_DATA/logs" "$WBM_DATA/home" "$WBM_DATA/tmp" \
    "$WBM_DATA/go/pkg/mod" "$WBM_DATA/go/cache" "$WBM_DATA/go/tmp" \
    "$WBM_DATA/etc" \
    2>/dev/null || true
  chmod 700 "$WBM_DATA" 2>/dev/null || true
  chmod 1777 "$WBM_DATA/tmp" 2>/dev/null || true
}
